"""Owner-authorized short-lived review copies in PRIVATE GitHub.

The public site and GitHub Actions artifacts never contain plaintext. Originals
remain owner-encrypted. Only files previously generated by the editorial agent
and present in its review folder are copied; this module cannot generate content.

Warning: deleting files in Git does not expunge historical Git objects. Retention
removes live references only; sensitive owners should prefer encrypted transport.
"""
import argparse
from datetime import date, timedelta
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
from tempfile import TemporaryDirectory

from .editorial_memory import digest
from .editorial_providers import Blocked
from .editorial_scene_qa import require_packet_rows

ROOT = Path(__file__).resolve().parents[1]
PRIVATE_REPO = "kaokshi/zen-editorial-review"
CHANNELS = ("science-01", "legends-01", "cinema-01")
MAX_FILE = 9_000_000
MAX_TOTAL = 48_000_000
APPROVAL_FILE = ROOT / "config" / "editorial_chat_plaintext.json"


def approval():
    config = json.loads(APPROVAL_FILE.read_text(encoding="utf-8"))
    if (config.get("enabled") is not True or config.get("owner_approved") is not True
            or config.get("repository") != PRIVATE_REPO
            or config.get("retention_days") != 7):
        raise Blocked("owner_plaintext_review_not_authorized")
    return config


def checked_day(day):
    if not isinstance(day, str) or not re.fullmatch(r"20[0-9]{2}-[0-9]{2}-[0-9]{2}", day):
        raise Blocked("invalid_private_review_date")
    try:
        date.fromisoformat(day)
    except ValueError:
        raise Blocked("invalid_private_review_date") from None
    return day


def run(argv, env, *, timeout=60):
    try:
        value = subprocess.run(argv, env=env, text=True, capture_output=True,
                               timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired):
        raise Blocked("private_review_transport_unavailable") from None
    if value.returncode:
        # Do not surface captured stderr or stdout: they may contain secrets.
        raise Blocked("private_review_transport_rejected")
    return value.stdout.strip()



def push_private_main(args, env, *, execute=run):
    """Preserve private writes when another writer advanced main."""
    try:
        execute([*args, "push", "origin", "HEAD:refs/heads/main"], env, timeout=120)
        return
    except Blocked:
        execute([*args, "fetch", "origin", "main"], env, timeout=90)
    try:
        execute([*args, "-c", "user.name=Zen Editorial Bot",
                 "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com",
                 "rebase", "FETCH_HEAD"], env, timeout=90)
    except Blocked:
        try:
            execute([*args, "rebase", "--abort"], env)
        except Blocked:
            pass
        raise
    execute([*args, "push", "origin", "HEAD:refs/heads/main"], env, timeout=120)


def connect(token, root, *, execute=run):
    if not token:
        raise Blocked("private_review_token_missing")
    env = {**os.environ, "GH_TOKEN": token, "GIT_TERMINAL_PROMPT": "0"}
    result = execute(["gh", "api", f"repos/{PRIVATE_REPO}"], env)
    try:
        metadata = json.loads(result)
    except ValueError:
        raise Blocked("private_review_repository_unverified") from None
    if metadata.get("visibility") != "private" or metadata.get("full_name") != PRIVATE_REPO:
        raise Blocked("private_review_repository_not_private")
    default = metadata.get("default_branch")
    if default != "main":
        raise Blocked("private_review_unexpected_default_branch")
    git = ["git", "-c", "credential.helper=", "-c",
           "credential.helper=!gh auth git-credential"]
    execute([*git, "clone", "--depth", "1", "--no-tags", "--branch", "main",
             "https://github.com/" + PRIVATE_REPO + ".git", str(root)], env, timeout=90)
    actual = execute([*git, "-C", str(root), "remote", "get-url", "origin"], env)
    if actual != "https://github.com/" + PRIVATE_REPO + ".git":
        raise Blocked("private_review_remote_mismatch")
    return git, env


def inputs(root, day, *, ready_only=False):
    """Enumerate only the existing agent-built review files."""
    base = Path(root) / checked_day(day) / "review"
    result = []
    total = 0
    for channel in CHANNELS:
        folder = base / channel
        if not folder.is_dir() or folder.is_symlink():
            continue
        names = ("Статья.docx", "Статья.html", "Статья.md",
                 "Текст для SHA-256.txt", "Статус и проверки.json", "SHA256SUMS.txt", "image_qa.json")
        checks = folder / "Статус и проверки.json"
        manifest = folder / "SHA256SUMS.txt"
        if not (checks.is_file() and manifest.is_file()):
            continue
        try:
            report = json.loads(checks.read_text(encoding="utf-8"))
            if ready_only and report.get("status") != "review_pending":
                continue
            rows = report.get("images", [])
            if not isinstance(rows, list):
                raise ValueError()
        except (ValueError, OSError):
            raise Blocked("private_review_report_invalid") from None
        files = [folder / name for name in names if (folder / name).is_file()]
        if any(not (folder / required).is_file() for required in (
                "Статья.docx", "Статья.html", "Текст для SHA-256.txt",
                "Статус и проверки.json", "SHA256SUMS.txt")):
            raise Blocked("private_review_required_files_missing")
        # Reject corrupted or partly modified editorial packages before exposing
        # any readable copy. The owner may still receive an explicitly incomplete
        # article if the producer itself labeled it as such.
        source = (folder / "Текст для SHA-256.txt").read_bytes()
        if digest(source) != report.get("text_sha256"):
            raise Blocked("private_review_canonical_sha_mismatch")
        require_packet_rows(rows, report["text_sha256"], article_id=channel)
        if report.get("status") in {"review_pending", "rights_review_pending"}:
            from .editorial_package import final_visual_gate

            final_visual_gate(report.get("visual_article"), rows, report["text_sha256"], channel,
                              lambda name: (folder / "images" / name).read_bytes(),
                              encoded=((folder / "Статья.html").read_bytes(), (folder / "Статья.docx").read_bytes()))
        expected = {}
        for line in manifest.read_text(encoding="utf-8").splitlines():
            parts = line.split("  ", 1)
            if len(parts) != 2 or not re.fullmatch(r"[a-f0-9]{64}", parts[0]):
                raise Blocked("private_review_manifest_invalid")
            expected[parts[1]] = parts[0]
        for image in rows:
            name = image.get("file") if isinstance(image, dict) else None
            if not isinstance(name, str) or not re.fullmatch(r"[a-zA-Z0-9._-]+\.(jpg|jpeg|png|webp)", name):
                raise Blocked("private_review_image_name_invalid")
            file = folder / "images" / name
            if not file.is_file() or file.is_symlink() or digest(file.read_bytes()) != image.get("sha256"):
                raise Blocked("private_review_image_sha_mismatch")
            files.append(file)
        seen = {p.relative_to(folder).as_posix() for p in files
                if p.name != "SHA256SUMS.txt"}
        # The complete original manifest also includes the model's historical
        # versions; avoid exposing those auxiliary files in the chat transport.
        if not seen <= expected.keys() or any(
                digest((folder / name).read_bytes()) != expected[name] for name in seen):
            raise Blocked("private_review_manifest_mismatch")
        for path in files:
            if path.is_symlink() or not path.resolve().is_relative_to(folder.resolve()):
                raise Blocked("private_review_unsafe_file")
            n = path.stat().st_size
            if n > MAX_FILE:
                raise Blocked("private_review_file_too_large")
            total += n
            if total > MAX_TOTAL:
                raise Blocked("private_review_total_size_exceeded")
        result.append((channel, folder, files))
    return result


def prune_directory(base, today, days):
    """Remove expired LIVE review paths; Git object history cannot be erased."""
    removed = []
    if not base.exists():
        return removed
    for candidate in base.iterdir():
        if candidate.is_symlink():
            raise Blocked("unsafe_private_review_path")
        if not candidate.is_dir():
            continue
        try:
            created = date.fromisoformat(candidate.name)
        except ValueError:
            continue
        if created < today - timedelta(days=days):
            shutil.rmtree(candidate)
            removed.append(candidate.name)
    return removed


def publish(root, day, *, token, execute=run, now=None, ready_only=False):
    cfg = approval()
    checked_day(day)
    today = now or date.today()
    batch = inputs(root, day, ready_only=ready_only)
    if not batch:
        return {"status": "no_agent_review_files", "channels": [],
                "content_generated_by_assistant": False}
    with TemporaryDirectory(prefix="zen-chat-private-") as work:
        destination = Path(work) / "repo"
        git, env = connect(token, destination, execute=execute)
        private_root = destination / "editorial-chat-review"
        removed = prune_directory(private_root, today, cfg["retention_days"])
        published = []
        for channel, source, files in batch:
            output = private_root / day / channel
            # Preserve the owner-approved, independently generated
            # illustrations folder when a text-only review is delivered later.
            # Never count retained images as vetted for a new text SHA.
            if output.is_symlink():
                raise Blocked("unsafe_private_review_path")
            if output.exists() and not output.is_dir():
                raise Blocked("private_review_output_not_directory")
            for file in files:
                relative = file.relative_to(source)
                dst = output / relative
                if dst.is_symlink() or dst.parent.is_symlink():
                    raise Blocked("unsafe_private_review_file")
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(file, dst)
            published.append(channel)
        args = [*git, "-C", str(destination)]
        execute([*args, "add", "--", "editorial-chat-review"], env)
        if execute([*args, "status", "--porcelain", "--", "editorial-chat-review"], env):
            execute([*args, "-c", "user.name=Zen Editorial Bot",
                     "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com",
                     "commit", "-m", "Owner-approved private chat review transport"], env)
            execute([*args, "push", "origin", "HEAD:refs/heads/main"], env, timeout=90)
        return {"status": "private_chat_review_available", "day": day,
                "channels": published, "expired_live_dates": removed,
                "repository": PRIVATE_REPO,
                "url": f"https://github.com/{PRIVATE_REPO}/tree/main/editorial-chat-review/{day}",
                "retention_days": cfg["retention_days"],
                "git_history_may_retain_deleted_content": True,
                "publication_authorized": False, "content_generated_by_assistant": False}


def cleanup(*, token, today=None, execute=run):
    cfg = approval()
    with TemporaryDirectory(prefix="zen-chat-retention-") as workspace:
        target = Path(workspace) / "repo"
        git, env = connect(token, target, execute=execute)
        removed = prune_directory(target / "editorial-chat-review",
                                  today or date.today(), cfg["retention_days"])
        if removed:
            args = [*git, "-C", str(target)]
            execute([*args, "add", "--", "editorial-chat-review"], env)
            execute([*args, "-c", "user.name=Zen Editorial Bot",
                     "-c", "user.email=41898282+github-actions[bot]@users.noreply.github.com",
                     "commit", "-m", "Expire private live review copies"], env)
            execute([*args, "push", "origin", "HEAD:refs/heads/main"], env, timeout=90)
        return {"status": "private_chat_review_cleanup_done", "expired_dates": removed,
                "git_history_may_retain_deleted_content": True}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("publish", "cleanup"))
    parser.add_argument("--root", type=Path)
    parser.add_argument("--date")
    parser.add_argument("--ready-only", action="store_true")
    args = parser.parse_args()
    token = os.environ.get("EDITORIAL_PRIVATE_TOKEN", "")
    if args.action == "publish":
        if not args.root or not args.date:
            raise Blocked("private_review_root_and_date_required")
        result = publish(args.root, args.date, token=token, ready_only=args.ready_only)
    else:
        result = cleanup(token=token)
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
